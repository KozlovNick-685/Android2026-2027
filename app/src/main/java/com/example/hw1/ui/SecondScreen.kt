package com.example.hw1.ui

import android.content.ClipData
import android.content.ClipboardManager
import android.content.Context
import androidx.compose.foundation.layout.*
import androidx.compose.material3.*
import androidx.compose.runtime.*
import androidx.compose.ui.Alignment
import androidx.compose.ui.Modifier
import androidx.compose.ui.platform.LocalContext
import androidx.compose.ui.text.input.PasswordVisualTransformation
import androidx.compose.ui.text.input.VisualTransformation
import androidx.compose.ui.unit.dp
import coil.compose.AsyncImage

private const val IMAGE_MATCH =
    "https://img.magnific.com/premium-vector/check-mark_1134661-28363.jpg?semt=ais_test_b&w=740&q=80"
private const val IMAGE_MISMATCH =
    "https://img.magnific.com/premium-vector/cross-check-symbol_875240-658.jpg?semt=ais_hybrid&w=740"

@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun SecondScreen(
    email: String,
    enteredPassword: String,
    generatedPassword: String,
    onBack: () -> Unit
) {
    val context = LocalContext.current
    val passwordsMatch = enteredPassword == generatedPassword

    var showGenerated by remember { mutableStateOf(false) }

    Scaffold(
        topBar = { TopAppBar(title = { Text("Результат") }) }
    ) { padding ->
        Column(
            modifier = Modifier
                .fillMaxSize()
                .padding(padding)
                .padding(24.dp),
            horizontalAlignment = Alignment.CenterHorizontally,
            verticalArrangement = Arrangement.Center
        ) {
            Text(
                text = if (passwordsMatch) "Пароль совпадает" else "Пароль не совпадает",
                style = MaterialTheme.typography.titleLarge
            )

            Spacer(Modifier.height(16.dp))

            AsyncImage(
                model = if (passwordsMatch) IMAGE_MATCH else IMAGE_MISMATCH,
                contentDescription = "Результат",
                modifier = Modifier
                    .fillMaxWidth()
                    .height(220.dp)
            )

            Spacer(Modifier.height(24.dp))

            Text(
                text = "Email: $email",
                style = MaterialTheme.typography.bodyLarge
            )

            Spacer(Modifier.height(16.dp))

            OutlinedTextField(
                value = generatedPassword,
                onValueChange = { },
                label = { Text("Сгенерированный пароль") },
                readOnly = true,
                singleLine = true,
                visualTransformation = if (showGenerated)
                    VisualTransformation.None
                else
                    PasswordVisualTransformation(),
                trailingIcon = {
                    TextButton(onClick = { showGenerated = !showGenerated }) {
                        Text(if (showGenerated) "Скрыть" else "Показать")
                    }
                },
                modifier = Modifier.fillMaxWidth()
            )

            Spacer(Modifier.height(8.dp))

            OutlinedButton(
                onClick = {
                    val clipboard = context
                        .getSystemService(Context.CLIPBOARD_SERVICE) as ClipboardManager
                    clipboard.setPrimaryClip(
                        ClipData.newPlainText("generated_password", generatedPassword)
                    )
                },
                modifier = Modifier.fillMaxWidth()
            ) {
                Text("Скопировать пароль")
            }

            Spacer(Modifier.height(24.dp))

            Button(
                onClick = onBack,
                modifier = Modifier.fillMaxWidth()
            ) {
                Text("Назад")
            }
        }
    }
}